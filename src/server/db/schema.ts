/**
 * Drizzle schema. This file is the source of truth for Postgres tables.
 *
 * Edit tables here, then `pnpm db:generate` to write a SQL migration in `drizzle/`,
 * then `pnpm db:migrate` to apply it. `pnpm db:push` doesn't make a migration and
 * instead applies the schema directly to the database.
 *
 * `.references()` is the foreign key. `relations()` below is only for
 * `db.query.*({ with: { ... } })` and does not change the database.
 *
 * Two column styles exist on purpose:
 * - App tables (`post`, `project`) use the callback form `(d) => ({ ... })`.
 *   Object keys become column names, so `createdAt` stays camelCase in SQL.
 * - Better Auth tables pass explicit snake_case names (`"user_id"`). Do not
 *   rename those columns; the auth adapter expects them.
 *
 * `$defaultFn` / `$onUpdate` run in JavaScript when Drizzle issues the write.
 * `.default(false)` is a SQL `DEFAULT`. Raw SQL updates will not bump
 * `$onUpdate` columns.
 */
import { relations } from "drizzle-orm";
import {
  boolean,
  index,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
} from "drizzle-orm/pg-core";

/**
 * Example table for the `post` router.
 *
 * `generatedByDefaultAsIdentity()` is Postgres identity (`GENERATED BY DEFAULT
 * AS IDENTITY`). `.references(() => user.id)` is the Foreign Key;
 * the callback (t => [...]) is lazy so `user` can be declared later in this file.
 */
export const posts = pgTable(
  "post",
  (d) => ({
    id: d.integer().primaryKey().generatedByDefaultAsIdentity(),
    name: d.varchar({ length: 256 }),
    createdById: d
      .varchar({ length: 255 })
      .notNull()
      .references(() => user.id),
    createdAt: d
      .timestamp({ withTimezone: true })
      .$defaultFn(() => new Date())
      .notNull(),
    updatedAt: d.timestamp({ withTimezone: true }).$onUpdate(() => new Date()),
  }),
  (t) => [
    index("created_by_idx").on(t.createdById),
    index("name_idx").on(t.name),
  ],
);

