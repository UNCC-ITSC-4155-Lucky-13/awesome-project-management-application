/**
 * Postgres enum for `project_role`.
 *
 * `owner` can delete the project.
 * `admin` and `owner` can change settings.
 * `member` is the default for everyone else.
 */
export const projectRole = pgEnum("project_role", ["owner", "admin", "member"]);

/**
 * Project/workspaces for project management
 */
export const projects = pgTable("project", (d) => ({
  id: d.uuid().primaryKey().defaultRandom(),
  name: d.varchar({ length: 255 }).notNull(),
  description: d.text(),
  sprintsEnabled: d.boolean().default(false).notNull(),
  sprintDuration: d.integer().default(2).notNull(),
  sprintStartDate: d.timestamp({ withTimezone: true }),
  createdAt: d
    .timestamp({ withTimezone: true })
    .$defaultFn(() => new Date())
    .notNull(),
  updatedAt: d.timestamp({ withTimezone: true }).$onUpdate(() => new Date()),
}));

/**
 * Project members/roles
 */
export const projectMembers = pgTable(
  "project_member",
  (d) => ({
    projectId: d
      .uuid()
      .notNull()
      .references(() => projects.id, { onDelete: "cascade" }),
    userId: d
      .text()
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    role: projectRole().default("member").notNull(),
  }),
  (t) => [
    primaryKey({
      name: "project_member_pk",
      columns: [t.projectId, t.userId],
    }),
    index("project_member_user_id_idx").on(t.userId),
  ],
);

/**
 * Relations for the user table.
 *
 * Defining relations here allows us to use them in the database queries. Example:
 * `db.query.user.findFirst({ with: { account: true } })` returns a user with
 * their account data.
 */
export const userRelations = relations(user, ({ many }) => ({
  account: many(account),
  session: many(session),
  projectMembers: many(projectMembers),
}));

/** Relations for the projects table. */
export const projectsRelations = relations(projects, ({ many }) => ({
  members: many(projectMembers), //
}));

/**
 * Relations for the projectMembers table.
 */
export const projectMembersRelations = relations(projectMembers, ({ one }) => ({
  project: one(projects, {
    fields: [projectMembers.projectId],
    references: [projects.id],
  }),
  user: one(user, {
    fields: [projectMembers.userId],
    references: [user.id],
  }),
}));

/** Relations for the account table. */
export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, { fields: [account.userId], references: [user.id] }),
}));

/** Relations for the session table. */
export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, { fields: [session.userId], references: [user.id] }),
}));
